function exhibit(siteId,id,number,title,era,hallId,form,sourceKey,media,paragraphs,details,object) {
  const [periodNote,feature,look,story] = paragraphs;
  const [motifs,first,second] = details;
  const refs = [ref[sourceKey],siteId==='yungang'?ref.ymap:ref.plan];
  const common={id,siteId,number,title,era,hallId,form,periodNote,feature,look,story,motifs:motifs.split('／'),chapters:[{title:first[0],body:first[1]},{title:second[0],body:second[1]}],sourceName:refs[0][0],source:link(refs[0]).url,sources:refs.map(link)};
  if(object) Object.assign(common,{objectType:'馆藏文物',holding:object[0],accession:object[1]});
  const [key,alt,x,y,point,body]=media;
  if(photos[key]) {
    common.image=root+key+'.webp';common.alt=alt;common.credit=photos[key];
    common.hotspots=[{x,y,title:point,body,source:common.source}];
    if(common.credit.source!==common.source)common.sources.push({label:'本幅影像档案与许可',url:common.credit.source});
  } else {
    common.studyPlate=root+key+'.svg';common.studyPlateAlt=alt;common.studyPlateNote='依据研究及馆藏记录绘制的关系图解；图形不表示原作尺寸、轮廓或保存状况。';common.mediaPage=common.source;common.mediaPageName='查阅研究原图与馆藏记录';common.hotspots=[];
  }
  works.push(common);
  return common;
}
