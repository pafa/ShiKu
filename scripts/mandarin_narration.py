DIGITS = "零一二三四五六七八九"


def cardinal(number):
    """Read a cave number, plate number, or the whole part of a measurement."""
    if not 0 <= number < 10000:
        raise ValueError(f"Unreviewed number in guide: {number}")
    if number == 0:
        return DIGITS[0]
    result = ""
    zero = False
    for place, unit in ((1000, "千"), (100, "百"), (10, "十"), (1, "")):
        digit, number = divmod(number, place)
        if digit:
            if zero:
                result += "零"
            if not (place == 10 and digit == 1 and not result):
                result += DIGITS[digit]
            result += unit
        zero = bool(result and not digit and number)
    return result


def measure(match):
    whole, dot, fraction = match[0].partition(".")
    return cardinal(int(whole)) + ("点" + "".join(DIGITS[int(n)] for n in fraction) if dot else "")


