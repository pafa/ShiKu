# A synthesis-only reading for ambiguous characters. Keep these out of captions,
# filenames, museum search, and attribution. These are replacements, not annotations
# that the narrator would read twice. The 'standard' field keeps the human-readable spelling.
READINGS = (
    ("迦叶", "迦摄"), ("平棊", "平棋"), ("须阇提", "须舌提"),
    ("于阗", "于田"), ("王玠", "王介"), ("胁侍", "协侍"),
    ("吐蕃", "土波"), ("龛", "勘"), ("伎乐", "伎月"), ("乐伎", "月伎"),
)


def prepare(text):
    standard = text
    for original, oral in PHRASES:
        standard = standard.replace(original, oral)
    standard = standard.replace("〇", "零")
    standard = re.sub(r"[0-9]{3,4}(?=年)", lambda m: "".join(DIGITS[int(n)] for n in m[0]), standard)
    standard = re.sub(r"[0-9]+(?:\.[0-9]+)?", measure, standard)
    standard = standard.replace("；", "。").replace("：", "，")
    standard = standard.translate(str.maketrans("", "", "《》「」“”"))
    if re.search(r"[a-zA-Z（）]", standard):
        raise ValueError(f"Review non-Mandarin text or parentheses before recording: {standard}")
    spoken = standard
    for original, reading in READINGS:
        spoken = spoken.replace(original, reading)
    return standard, spoken


def narration_rows():
    source = """
        import {caves} from './cave-plan.js';
        console.log(JSON.stringify(caves.flatMap(c => c.details.map(d => ({
          name: c.id + '--' + d.id, text: d.text
        })))));
    """
    rows = json.loads(subprocess.check_output(["node", "--input-type=module", "-e", source], cwd=ROOT))
    for row in rows:
        row["standard"], row["spoken"] = prepare(row["text"])
    return rows


if __name__ == "__main__":
    print(json.dumps(narration_rows(), ensure_ascii=False, indent=2))
