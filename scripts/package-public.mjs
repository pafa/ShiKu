// Build the distributable tree from named source paths and hashes of approved media.
// Use an empty destination. Never modify the local collection or reuse a stale export.
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {mkdir, readdir, readFile, writeFile, realpath, stat, lstat, mkdtemp, rename, rm} from 'node:fs/promises';
import {dirname, join, resolve, relative, isAbsolute, sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import {caves} from '../cave-plan.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outArg = process.argv.indexOf('--out');
if (outArg < 0 || !process.argv[outArg + 1]) throw Error('用法：node scripts/package-public.mjs --out <新的候选目录>');
const requested = resolve(process.argv[outArg + 1]);
const parent = await realpath(dirname(requested));
const destination = join(parent, relative(dirname(requested),requested));
if (destination === root || root.startsWith(destination+sep) ||
    (destination.startsWith(root+sep) && !destination.startsWith(join(root,'release-output')+sep)))
  throw Error('请选择工作区外的新目录，或先创建专用 release-output 父目录');
let previous;
try { previous = await lstat(destination); } catch(e) { if(e.code!=='ENOENT') throw e; }
if (previous && (!previous.isDirectory() || (await readdir(destination)).length)) throw Error('输出必须是尚不存在或为空的普通目录');
const sources = JSON.parse(await readFile(join(root,'release/public-sources.json')));
const entries = JSON.parse(await readFile(join(root,'release/public-assets.json'))).files;
const credits = new Map();
const originalContent = {license:'CC BY 4.0', licenseUrl:'https://creativecommons.org/licenses/by/4.0/', credit:'ShiKu'};
const sha = buffer => createHash('sha256').update(buffer).digest('hex');
function safePath(path) {
  if(typeof path!=='string'||isAbsolute(path)||path.includes('\\')||path.split('/').some(c=>!c||c==='..'||c==='.'))throw Error('无效的清单路径 '+path);
  return path;
}
async function input(path){
  const target = join(root,safePath(path));
  if (await realpath(target)!==target || !(await stat(target)).isFile())throw Error('不是普通的仓库文件 '+path);
  return readFile(target);
}
async function save(path,bytes){
  const file=join(stage,safePath(path));
  await mkdir(dirname(file),{recursive:true});
  await writeFile(file,bytes);
}
async function include(entry){
  if(credits.has(entry.path))throw Error('重复登记 '+entry.path);
  const bytes = await input(entry.path);
  if(!entry.credit || !entry.source || !entry.license || sha(bytes)!==entry.sha256)throw Error('素材许可或哈希不符 '+entry.path);
  await save(entry.path,bytes);
  credits.set(entry.path,entry);
}
async function inventory(dir,relativePath=''){
  const rows=[];
  for(const e of (await readdir(dir,{withFileTypes:true})).sort((a,b)=>a.name<b.name?-1:1)){
    const path=[relativePath,e.name].filter(Boolean).join('/');
    if(e.isDirectory())rows.push(...await inventory(join(dir,e.name),path));
    else rows.push(sha(await readFile(join(dir,e.name)))+'  '+path);
  }
  return rows;
}
const stage = await mkdtemp(join(parent,'.shiku-package-'));
try {
  for (const path of sources) {
    const permittedText = /\.(?:m?js|html|css|jsonc?|txt|md|py|ya?ml|toml|service|conf)$/i.test(path) ||
      ['LICENSE','NOTICE','.gitattributes','.gitignore'].includes(path);
    if (!permittedText || path.split('/').some(part => /^(?:review|preview|node_modules|\.env|\.git|\.aws|\.codex|dist|secrets|LOCAL-WORKBENCH)(?:$|\.)/.test(part)))
      throw Error('该路径不能通过文本源码名单导出 '+path);
    const bytes = await input(path);
    new TextDecoder('utf-8',{fatal:true}).decode(bytes);
    if (bytes.includes(0)) throw Error('资料文件包含二进制数据 '+path);
    await save(path,bytes);
  }
  for (const entry of entries) await include(entry);
  const narrationDir='assets/walk/voices/';
  const recordings=JSON.parse(await input(narrationDir+'recordings.json'));
  const cues = caves.flatMap(cave => cave.details.map(detail => ({
    key: cave.id+'--'+detail.id, written: detail.text,
  }))).sort((a,b)=>a.key<b.key?-1:1);
  if(!cues.length || Object.keys(recordings).length!==cues.length)throw Error('录音数量与驻足点不一致');
  for(const {key:cue,written} of cues){
    const row=recordings[cue];
    if(row?.edition!=='cn-guide-2' || row.text!==sha(Buffer.from(written)) ||
       !row.transcript || !/^[a-f0-9]{64}$/.test(row.spoken) || !/^[a-f0-9]{64}$/.test(row.recipe))
      throw Error('讲解尚未完成本次普通话录制或与讲稿不一致 '+cue);
    if(!/^[a-z\d]+(?:-[a-z\d]+)*--[a-z\d-]+$/.test(cue))throw Error('无效的音频键');
    await include({path:narrationDir+cue+'.mp3',sha256:recordings[cue].audio,...originalContent,source:narrationDir+'SOURCES.md',changes:'由本站普通话讲稿生成；语音模型和声音身份不随录音转授。'});
  }
  const paths=Array.from(credits.keys()).sort();
  await save('public-media.js','// Generated by scripts/package-public.mjs.\nexport const publicEdition = true;\nconst paths = new Set('+JSON.stringify(paths)+');\nexport function hasDisplayMedia(path) { return paths.has(path); }\n');
  execFileSync(process.execPath,['scripts/build-guide.mjs'],{cwd:stage,stdio:'inherit'});
  const guideContent = {
    'exhibition-map.svg':'九馆总平面与展位图。',
    'exhibition-guide.html':'原创导览正文、编排与解读；第三方照片和引用按各件标注。',
    'CATALOG.md':'原创展签与解读；机构馆藏著录、图像及引用沿用各自条款。',
  };
  for (const [path,changes] of Object.entries(guideContent)) {
    credits.set(path,{path,sha256:sha(await readFile(join(stage,path))),...originalContent,
      source:'exhibition-guide.html',changes});
  }
  const all=[...credits.values()].sort((a,b)=>a.path<b.path?-1:1);
  await save('assets/credits.json',JSON.stringify({version:1,files:all},null,2)+'\n');
  const escape=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const link=(s,caption)=>'<a href="'+escape(/^https?:\/\//.test(s)?s:'/'+s)+'">'+escape(caption)+'</a>';
  const html=all.map(p=>'<tr><th scope="row">'+escape(p.path)+'</th><td>'+link(p.source,p.credit)+'</td><td>'+(p.licenseUrl?link(p.licenseUrl,p.license):escape(p.license))+'</td><td>'+escape(p.changes || '')+'</td></tr>').join('\n');
  await save('assets/credits.html','<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>ShiKu 素材署名</title><style>body{font:1rem/1.6 system-ui;max-width:90rem;margin:auto;padding:1rem}div{overflow-x:auto}table{border-collapse:collapse}td,th{padding:.55rem;text-align:left;vertical-align:top;border-bottom:1px solid #ccc;overflow-wrap:anywhere}a{color:#71411d}</style><main><a href="/">返回石窟</a><h1>展馆素材与署名</h1><p>每件素材沿用此处列出的使用条件，点击署名查看原作者或来源。</p><div><table><thead><tr><th>文件</th><th>署名与出处</th><th>使用条件</th><th>处理说明</th></tr></thead><tbody>'+html+'</tbody></table></div></main></html>');
  const rows=await inventory(stage);
  await save('SHA256SUMS',rows.join('\n')+'\n');
  await rename(stage,destination);
  console.log('公开候选：'+destination+'；'+all.length+' 项素材，'+(rows.length+1)+' 个文件。');
} catch(error) {
  await rm(stage,{recursive:true,force:true});
  throw error;
}
