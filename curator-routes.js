export function chaptersFor(hall){
  const stops=stopsFor(hall);
  const chapters=stops.map((lead,i)=>({...lead,theme:groups[hall.id][i][0],items:[]}));
  const terms=groups[hall.id].map(([,words])=>words.split(' '));
  hall.scenes.forEach((work,index)=>{
    let best=chapters.findIndex(c=>c.id===work.id);
    if(best<0){
      const field=[work.title,work.feature,work.periodNote,...work.motifs].join(' ');
      const scores=terms.map(words=>words.reduce((n,w)=>n+(work.title.includes(w)?3:0)+(field.includes(w)?1:0),0));
      best=scores.indexOf(Math.max(...scores));
    }
    chapters[best].items.push({work,index});
  });
  return chapters;
}
