export function stopsFor(hall){
  const tour=tours[hall.id];
  return tour.stops.map(([id,title,note])=>{
    const index=hall.scenes.findIndex(s=>s.id===id);
    if(index<0)throw Error('导览缺少展品 '+id);
    return {id,index,title,note,work:hall.scenes[index]};
  });
}

