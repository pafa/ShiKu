// Contemporary exhibition maquettes. Units belong to the model, not the original cave.
// at is the centre. An arch stands in the XY plane, opening towards +Z.
const shape = (shape, x, y, z, w, h, d, tone, yaw = 0) => ({
  shape, at: [x, y, z], size: [w, h, d], tone, yaw,
});
const box = (x, y, z, w, h, d, tone = 'stone', yaw) => shape('box', x, y, z, w, h, d, tone, yaw);
const cyl = (x, y, z, w, h, d, tone = 'stone', yaw) => shape('cylinder', x, y, z, w, h, d, tone, yaw);
const arch = (x, z, w, h, d = .18, tone = 'edge', yaw = 0, base = 0) =>
  shape('arch', x, base + h / 2, z, w, h, d, tone, yaw);
const panel = (x, y, z, w, h, tone = 'plaster', yaw = 0) =>
  shape('panel', x, y, z, w, h, .07, tone, yaw);
const foot = (x, z, w, d, h = .15, tone = 'edge', yaw = 0) => box(x, h / 2, z, w, h, d, tone, yaw);
const row = (n, start, end, make) => Array.from({length: n}, (_, i) => make(start + (end - start) * i / (n - 1), i)).flat();
const pair = make => [-1, 1].flatMap(make);
const column = (x, z, h, r = .11, tone = 'stone') => cyl(x, h/2, z, 2*r, h, 2*r, tone);
const station = (name, kind, intent, ...parts) => ({name, kind, intent, parts: parts.flat()});

// A cutaway lotus is used to show the difference between a ceiling carving and a floor motif.
function lotus(x, y, z, radius, count, tone) {
  const petals = Array.from({length: count}, (_, i) => {
    const angle = i * 2*Math.PI/count;
    return cyl(x+Math.sin(angle)*radius*.56, y, z+Math.cos(angle)*radius*.56,
      radius*.42, .08, radius*.92, tone, angle);
  });
  return [cyl(x,y+.025,z,radius*.52,.12,radius*.52,'brass'), ...petals];
}

