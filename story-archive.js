export const readingRoom = {};
for(const [site,scenes] of Object.entries({...eastRoutes,...westRoutes})){
  for(const s of scenes){
    const id=site+'-'+String(s.number).match(/\d+/)?.[0],entry=essays[id];
    if(!entry)continue;
    const sources=[{label:s.sourceName,url:s.source},...entry.sources];
    if(s.mediaPage&&s.mediaPage!==s.source)sources.push({label:s.mediaPageName||'相关馆藏记录',url:s.mediaPage});
    if((id==='maijishan-120'||id==='maijishan-165')&&s.credit?.source)sources.push({label:'名取洋之助 · 1956年现场照片',url:s.credit.source});
    if((id==='maijishan-127'||id==='maijishan-133')&&s.credit?.source)sources.push({label:'本展图版所据原刊',url:s.credit.source});
    readingRoom[id]={chapters:entry.chapters,sources:sources.filter((item,i,list)=>list.findIndex(v=>v.url.split('#')[0]===item.url.split('#')[0])===i)};
  }
}

for (const [id, revision] of Object.entries(maijiRevisions)) {
  const earlier = readingRoom[id];
  readingRoom[id] = {
    chapters:[...revision.chapters.map(ch => ({...ch, source:revision.sources[0]})), ...earlier.chapters],
    sources:[...new Map([...revision.sources, ...earlier.sources].map(item => [item.url, item])).values()]
  };
}

for(const work of additions){
  readingRoom[work.id]={chapters:work.chapters,sources:work.sources};
}


for (const [id, detail] of Object.entries(curatorialReadings)) {
  const reading = readingRoom[id];
  const source = detail.source || reading.sources[0];
  reading.chapters = [...reading.chapters, {...detail, source}];
  if (!reading.sources.some(item => item.url === source.url)) {
    reading.sources = [...reading.sources, source];
  }
}
